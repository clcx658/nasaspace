// Downloads the Stitch images (hot-linked from lh3.googleusercontent.com) into assets/img/ so the game
// no longer depends on Google's servers, and writes assets/img/manifest.js (original URL -> local file).
// Run once on a machine with internet access:   node tools/localize-images.js   then commit assets/img/.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const w = {}; new Function('window', fs.readFileSync(path.join(root, 'js', 'screens-data.js'), 'utf8'))(w);
const urls = new Set();
for (const s of Object.values(w.STITCH_SCREENS)) {
  for (const m of (s.html + s.style).matchAll(/https:\/\/lh3\.googleusercontent\.com\/[^"')\s]+/g)) urls.add(m[0]);
}
const outDir = path.join(root, 'assets', 'img'); fs.mkdirSync(outDir, { recursive: true });
const EXT = { 'image/png': 'png', 'image/jpeg': 'jpg', 'image/webp': 'webp', 'image/gif': 'gif', 'image/svg+xml': 'svg' };
(async () => {
  const map = {}; let i = 0, fail = 0;
  for (const u of urls) {
    i++;
    try {
      const r = await fetch(u); if (!r.ok) throw new Error('HTTP ' + r.status);
      const ext = EXT[(r.headers.get('content-type') || '').split(';')[0]] || 'png';
      const file = `stitch-${String(i).padStart(2, '0')}.${ext}`;
      fs.writeFileSync(path.join(outDir, file), Buffer.from(await r.arrayBuffer()));
      map[u] = 'assets/img/' + file; process.stdout.write('.');
    } catch (e) { fail++; console.warn('\nfailed:', u.slice(0, 70), e.message); }
  }
  fs.writeFileSync(path.join(outDir, 'manifest.js'), '/* Generated by tools/localize-images.js. Maps original Stitch image URLs to local files. */\nwindow.STITCH_IMAGE_MAP = ' + JSON.stringify(map, null, 1) + ';\n');
  console.log(`\n${Object.keys(map).length} images saved, ${fail} failed (${urls.size} found).`);
})();
