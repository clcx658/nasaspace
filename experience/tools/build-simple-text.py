#!/usr/bin/env python3
"""Builds js/simple-text.js (the plain-language text for ages 7-12) from data/simple-text.json.
Edit data/simple-text.json (original sentence -> simple sentence), then run:  python3 tools/build-simple-text.py
Use the value "__HIDE__" to hide an element."""
import json, re, os
here = os.path.dirname(os.path.abspath(__file__))
pairs = json.load(open(os.path.join(here, '..', 'data', 'simple-text.json'), encoding='utf8'))
norm = lambda t: ' '.join(t.split())
quote = re.compile(r'^["“”\']+|["“”\']+$')
simple = {}
for k, v in pairs.items():
    nk = norm(k); simple[nk] = v
    k2 = quote.sub('', nk)                       # the screens sometimes add or drop quote marks
    if k2 != nk: simple[k2] = quote.sub('', v) if v != '__HIDE__' else v
# [pattern, replacement, "cs" = case sensitive]. Hard words that are replaced anywhere they still appear.
words = [
 ["SIMULATED MISSION VALUES", "SIMULATED (PRETEND) MISSION VALUES", "cs"],
 ["Simulated mission values", "Simulated (pretend) mission values", "cs"],
 ["Simulated Mission Values", "Simulated (pretend) mission values", "cs"],
 ["\\bSol\\s+0?4\\b", "Day 1"], ["\\bSol\\b", "day"],
 ["\\bMoonbase\\b", "Moon base"], ["\\bregolith\\b", "Moon soil"], ["\\bECLSS\\b", "life support"], ["\\btelemetry\\b", "readings"],
 ["\\bmicrogravity\\b", "weak gravity"], ["\\belectrostatic\\b", "static"], ["\\bphotovoltaic\\b", "solar"],
 ["\\bnominal\\b", "normal"], ["\\boptimal\\b", "best"], ["\\bprotocols\\b", "rules"], ["\\bprotocol\\b", "rule"],
 ["\\bmodules\\b", "parts"], ["\\bmodule\\b", "part"], ["\\bsectors\\b", "areas"], ["\\bsector\\b", "area"],
 ["\\bhabitats\\b", "bases"], ["\\bhabitat\\b", "base"], ["\\bpressurized\\b", "sealed"], ["\\bpressurize\\b", "seal"],
 ["\\bLunar\\b", "Moon"], ["\\blunar\\b", "Moon"],
 ["\\bReadines\\b", "Readiness"],
 # one spelling style everywhere (British)
 ["\\bcozy\\b", "cosy"], ["\\bstabilizes\\b", "stabilises"], ["\\bcollectible\\b", "collectable"], ["\\bdefense\\b", "defence"],
 ["\\bcolors?\\b", "colour"], ["\\bmeters\\b", "metres"], ["\\bkilometers\\b", "kilometres"], ["\\banalyze\\b", "analyse"],
 ["\\bcenter\\b", "centre"], ["\\brecognized\\b", "recognised"],
]
out = """/* Plain-language text for children aged 7-12. GENERATED by tools/build-simple-text.py from data/simple-text.json. Do not edit by hand.
   The Stitch designs use long, technical sentences. This swaps them for short, simple ones while the screens are shown.
   - SIMPLE: exact sentence -> simple sentence ("__HIDE__" hides the element).
   - WORDS: hard words replaced anywhere they still appear. */
(function(){
  'use strict';
  var J = window.JAM = window.JAM || {};
  J.SIMPLE = %s;
  J.WORDS = %s;
})();
""" % (json.dumps(simple, ensure_ascii=False, indent=0), json.dumps(words, ensure_ascii=False))
open(os.path.join(here, '..', 'js', 'simple-text.js'), 'w', encoding='utf8').write(out)
print('built js/simple-text.js:', len(simple), 'sentences,', len(words), 'word rules')
