// Downloads Outfit + Material Symbols from Google Fonts into assets/fonts and writes css/fonts.css.
// Run once: node tools/fetch-fonts.js   (needs internet + curl). Output files are committed, so the game works offline.
const { execFileSync } = require('child_process');
const fs = require('fs'), path = require('path');
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const out = path.join(__dirname, '..', 'assets', 'fonts');
fs.mkdirSync(out, { recursive: true });
const curl = (...a) => execFileSync('curl', ['-sS', '-m', '90', '-A', UA, ...a], { maxBuffer: 1 << 28 });

let css = '/* Generated by tools/fetch-fonts.js. Self-hosted fonts (Outfit, Material Symbols Outlined). */\n';

// Outfit: keep only the "latin" subset to stay small
const outfitCss = curl('https://fonts.googleapis.com/css2?family=Outfit:wght@400;500;600;700;800;900&display=swap').toString();
const re = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
let m;
while ((m = re.exec(outfitCss))) {
  if (m[1] !== 'latin') continue; // keep only the "latin" subset to stay small
  const url = /url\((https:[^)]+)\)/.exec(m[2])[1];
  // Google serves one variable font file for every weight, so download it once.
  fs.writeFileSync(path.join(out, 'outfit.woff2'), curl(url));
  css += `@font-face{font-family:'Outfit';font-style:normal;font-weight:100 900;font-display:swap;src:url(../assets/fonts/outfit.woff2) format('woff2');}\n`;
  break;
}

// Material Symbols Outlined (weight 400, variable FILL)
const msCss = curl('https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@24,400,0..1,0&display=block').toString();
const msUrl = /url\((https:[^)]+)\)/.exec(msCss)[1];
fs.writeFileSync(path.join(out, 'material-symbols.woff2'), curl(msUrl));
css += `@font-face{font-family:'Material Symbols Outlined';font-style:normal;font-weight:400;font-display:block;src:url(../assets/fonts/material-symbols.woff2) format('woff2');}\n`;
css += `.material-symbols-outlined{font-family:'Material Symbols Outlined';font-weight:normal;font-style:normal;font-size:24px;line-height:1;letter-spacing:normal;text-transform:none;display:inline-block;white-space:nowrap;word-wrap:normal;direction:ltr;-webkit-font-feature-settings:'liga';font-feature-settings:'liga';-webkit-font-smoothing:antialiased;}\n`;
fs.writeFileSync(path.join(__dirname, '..', 'css', 'fonts.css'), css);
console.log('fonts written:', fs.readdirSync(out).join(', '));
