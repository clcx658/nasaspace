#!/usr/bin/env python3
"""Scopes the classic game's mini-game CSS under #mg so it cannot clash with the Stitch/Tailwind styles.
Usage: python3 tools/scope-css.py ../css/style.css css/minis.css"""
import re, sys

SKIP_SEL = re.compile(r'^(html|body|main|h1|h2|h3|p|a|button|\*|\[hidden\]|\.btn.*|\.link|\.cta|\.row-end|:focus-visible|\.say.*|\.bubble.*|\.hud.*|\.snd|\.dots.*|\.clock|\.meters?.*|\.final.*|\.m-.*|\.fill|\.bar|\.delta.*|\.sim|\.welcome.*|\.scene.*|\.intro|\.how.*|\.best|\.float|\.wave|#stars.*|\.letter.*|\.q-.*|\.opts|\.opt.*|\.tf|\.match.*|\.tour.*|\.fac.*|\.night.*|\.res-.*|\.award|\.ending-s|\.quote|\.scorebox|\.srow.*|\.picks.*|\.learn.*|details.*|\.nasa.*|\.confetti|\.card|\.banner.*|\.tag.*|\.story|\.chips?.*|\.warnline|\.fact.*|\.choices.*|\.choice.*|\.opt-.*|\.sky.*|\.rocket.*|\.status)$')

def split_top(css):
    out, i, depth, start = [], 0, 0, 0
    while i < len(css):
        c = css[i]
        if c == '{': depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0: out.append(css[start:i+1]); start = i+1
        i += 1
    return out

def scope_sel(sel):
    parts = [p.strip() for p in sel.split(',')]
    keep = []
    for p in parts:
        base = re.split(r'[\s:>+~\[]', p)[0] or p
        if SKIP_SEL.match(p) or SKIP_SEL.match(base): continue
        keep.append('#mg ' + p)
    return ','.join(keep)

def process(css):
    res = []
    for blk in split_top(css):
        blk = blk.strip()
        if not blk: continue
        head, body = blk.split('{', 1)
        head = head.strip(); body = body[:-1]
        if head.startswith('@keyframes') or head.startswith('@font-face'):
            res.append(blk)
        elif head.startswith('@media'):
            inner = process(body)
            if inner.strip(): res.append(head + '{' + inner + '}')
        elif head.startswith(':root'): continue
        else:
            s = scope_sel(head)
            if s: res.append(s + '{' + body + '}')
    return '\n'.join(res)

src = open(sys.argv[1]).read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
out = '/* Generated by tools/scope-css.py: classic mini-game styles scoped under #mg */\n#mg{--bg:#070d27;--card:#15215a;--card2:#1c2b73;--line:#33449a;--text:#f3f6ff;--muted:#b9c4f2;--cyan:#4fe3ff;--yellow:#ffd24d;--green:#62f0a0;--orange:#ff9a4d;--red:#ff5d73;--blue:#6f8cff;--radius:22px;font-family:Outfit,"Trebuchet MS",system-ui,sans-serif;color:var(--text);font-size:17px;line-height:1.4}\n#mg *{box-sizing:border-box}\n#mg button{font:inherit;color:inherit;cursor:pointer;touch-action:manipulation}\n#mg [hidden]{display:none!important}\n#mg .btn{display:inline-block;border:0;border-radius:999px;padding:14px 30px;min-height:52px;font-weight:800;color:#1a1240;background:linear-gradient(180deg,#ffe27a,#ffb832);box-shadow:0 5px 0 #c98512}\n#mg .cta{text-align:center;margin:14px 0 4px}\n#mg .opt{border-radius:16px;padding:12px 16px;font-weight:800;text-align:left;border:3px solid #4a5fd0;background:linear-gradient(180deg,#26378f,#1b2a76);box-shadow:0 4px 0 #101a55}\n#mg .opt.ok{border-color:var(--green);background:rgba(98,240,160,.25)}\n#mg .opt.no{border-color:var(--red);background:rgba(255,93,115,.2)}\n#mg .opts{display:grid;gap:10px}\n#mg .hintline{background:rgba(79,227,255,.12);border-left:6px solid var(--cyan);padding:6px 12px;border-radius:10px;margin:10px 0;font-weight:700;font-size:.95rem}\n#mg .tray .item,#mg .igrid .item{}\n#mg .shake{animation:shake .4s}\n@keyframes shake{20%{transform:translateX(-6px)}40%{transform:translateX(6px)}60%{transform:translateX(-4px)}80%{transform:translateX(4px)}}\n#mg .chips{display:flex;gap:6px;flex-wrap:wrap}\n'
out += process(src)
open(sys.argv[2], 'w').write(out + '\n')
print('written', sys.argv[2], len(out), 'bytes')
