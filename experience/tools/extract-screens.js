// Reads the Google Stitch export and generates:
//   js/screens-data.js   (markup, custom CSS and script of each of the 27 screens)
//   tailwind.config.js   (all 27 Tailwind configs merged into one)
// Run: node tools/extract-screens.js
const fs = require('fs'), path = require('path'), vm = require('vm');
const SRC = path.join(__dirname, '..', '..', 'stitch_moonbase_mission_game_ui');
const OUT = path.join(__dirname, '..');

function deepMerge(a, b) {
  for (const k of Object.keys(b)) {
    if (b[k] && typeof b[k] === 'object' && !Array.isArray(b[k])) a[k] = deepMerge(a[k] && typeof a[k] === 'object' ? a[k] : {}, b[k]);
    else a[k] = b[k];
  }
  return a;
}
const dirs = fs.readdirSync(SRC).filter(d => /_(\d+)\._/.test(d) || /moon_(\d+)\./.test(d))
  .map(d => ({ d, n: +/moon_(\d+)\./.exec(d)[1] })).sort((x, y) => x.n - y.n);

const screens = {}; let cfg = {};
for (const { d, n } of dirs) {
  const file = path.join(SRC, d, 'code.html');
  if (!fs.existsSync(file)) continue;
  const html = fs.readFileSync(file, 'utf8');
  const title = (/<title>([\s\S]*?)<\/title>/.exec(html) || [, ''])[1].trim();
  const styles = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map(m => m[1]).join('\n');
  const scripts = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(m => m[1]);
  let appJs = '';
  for (const s of scripts) {
    if (/tailwind\.config\s*=/.test(s)) {
      const body = s.replace(/^[\s\S]*?tailwind\.config\s*=\s*/, '').replace(/;?\s*$/, '');
      try { cfg = deepMerge(cfg, vm.runInNewContext('(' + body + ')', {}, { timeout: 1000 })); } catch (e) { console.warn('config parse failed for', n, e.message); }
    } else appJs += s + '\n';
  }
  const bodyM = /<body([^>]*)>([\s\S]*)<\/body>/.exec(html);
  const bodyClass = (/class="([^"]*)"/.exec(bodyM[1]) || [, ''])[1];
  let inner = bodyM[2].replace(/<script[\s\S]*?<\/script>/g, '');
  screens[n] = { dir: d, title, bodyClass, style: styles, html: inner.trim(), js: appJs.trim() };
}
fs.writeFileSync(path.join(OUT, 'js', 'screens-data.js'),
  '/* Generated by tools/extract-screens.js from the Google Stitch export. Do not edit by hand. */\n' +
  'window.STITCH_SCREENS = ' + JSON.stringify(screens) + ';\n');

cfg.content = ['./index.html', './js/**/*.js'];
cfg.plugins = ['@@forms', '@@container'];
let txt = 'module.exports = ' + JSON.stringify(cfg, null, 2) + ';\n';
txt = txt.replace('"@@forms"', "require('@tailwindcss/forms')").replace('"@@container"', "require('@tailwindcss/container-queries')");
fs.writeFileSync(path.join(OUT, 'tailwind.config.js'), '// Generated by tools/extract-screens.js (merged from the 27 Stitch screens).\n' + txt);
console.log('screens:', Object.keys(screens).length, '| colour tokens:', Object.keys((cfg.theme && cfg.theme.extend && cfg.theme.extend.colors) || {}).length);
